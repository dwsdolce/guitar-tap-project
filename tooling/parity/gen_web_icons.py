"""Write the web's Material Design icon paths from the font the Python edition draws its icons with, and the app's
own icons into both editions.

The Python edition draws its icons with qtawesome's Material Design Icons font ("mdi.…"); the web draws SVG.
So that both show the same shapes, each icon the web uses is read from that font's glyph and written as an SVG
path in a 24 × 24 viewBox to GuitarTapWeb/src/components/mdiPaths.ts. Each is the nearest Material Design icon
to the SF Symbol Swift uses for the same control.

The app's own icons — for the SF Symbols with no Material Design equivalent — are drawn once, as SVG in
tooling/parity/icons/ (24 × 24, stroked in currentColor). Each is written to GuitarTapWeb/src/components/customIcons.ts
(its inner markup, drawn in the web's icon frame) and to the Python edition's views/utilities/custom_icons.py (the
whole SVG, drawn by palette.icon in a role's colour as "gt.<name>").

Run with the Python edition's interpreter (it has qtawesome and fontTools):

    ../guitar_tap/.venv/bin/python tooling/parity/gen_web_icons.py
"""
