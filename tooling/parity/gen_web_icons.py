#!/usr/bin/env python3
"""Write the web's Material Design icon paths from the font the Python edition draws its icons with.

The Python edition draws its icons with qtawesome's Material Design Icons font ("mdi.…"); the web draws SVG.
So that both show the same shapes, each icon the web uses is read from that font's glyph and written as an SVG
path in a 24 × 24 viewBox to GuitarTapWeb/src/components/mdiPaths.ts. Each is the nearest Material Design icon
to the SF Symbol Swift uses for the same control.

Run with the Python edition's interpreter (it has qtawesome and fontTools):

    ../guitar_tap/.venv/bin/python tooling/parity/gen_web_icons.py
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import qtawesome
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

sys.path.insert(0, str(Path(__file__).resolve().parent))
import platforms  # noqa: E402

# The web's name → the Material Design icon, as Python names it ("mdi.<name>").
ICONS = {
    "tap": "gesture-tap",
    "pauseCircle": "pause-circle-outline",
    "playCircle": "play-circle-outline",
    "closeCircle": "close-circle-outline",
    "checkCircle": "check-circle-outline",
    "checkCircleFill": "check-circle",
    "rotate3d": "rotate-3d-variant",
    "restore": "restore",
    "autoDb": "swap-vertical-circle-outline",
    "autoDbOn": "swap-vertical-circle",
    "eye": "eye-outline",
    "star": "star",
    "eyeOff": "eye-off-outline",
    "save": "download-outline",
    "clipboard": "clipboard-list-outline",
    "chartBar": "chart-bar",
    "cog": "cog-outline",
    "help": "help-circle-outline",
    "bookOpen": "book-open-variant",
    "waveform": "waveform",
    "musicNote": "music-note",
    "refresh": "refresh",
    "autoFix": "auto-fix",
    "chartLine": "chart-line",
    "document": "file-document-outline",
    "wind": "weather-windy",
    "arrowUpDown": "arrow-up-down",
    "square": "square",
    "circleHalf": "circle-half-full",
    "tag": "tag",
}

FONT = "materialdesignicons5-webfont-5.9.55.ttf"
CHARMAP = "materialdesignicons5-webfont-charmap-5.9.55.json"


def main() -> int:
    fonts = Path(os.path.dirname(qtawesome.__file__)) / "fonts"
    font = TTFont(fonts / FONT)
    charmap = json.loads((fonts / CHARMAP).read_text())
    em = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = 24 / em
    lines = [
        "// GENERATED by guitar-tap-project/tooling/parity/gen_web_icons.py — do not edit by hand.",
        "// The Material Design icons the Python edition draws (qtawesome \"mdi.…\"), as SVG paths in a",
        "// 24 × 24 viewBox, so the web shows the same shapes.",
        "export const MDI = {",
    ]
    for key, name in ICONS.items():
        glyph = cmap[int(charmap[name], 16)]
        pen = SVGPathPen(glyphs)
        # Font units, y up, baseline at 0 → a 24 × 24 box, y down, top at the ascent.
        glyphs[glyph].draw(TransformPen(pen, (scale, 0, 0, -scale, 0, ascent * scale)))
        path = pen.getCommands()
        lines.append(f"  {key}: '{path}', // mdi.{name}")
    lines.append("} as const")
    lines.append("")
    out = {p.key: p.root for p in platforms.PLATFORMS}["web"] / "src/components/mdiPaths.ts"
    out.write_text("\n".join(lines))
    print(f"wrote {len(ICONS)} icons to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
