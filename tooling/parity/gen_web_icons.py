# The app's own icons: the web's name → the SVG in tooling/parity/icons/ (Python names it "gt.<file stem>").
CUSTOM = {
    "ringMode": "ring-mode",  # circle.dashed
    "plusViewfinder": "plus-viewfinder",  # plus.viewfinder
    "dotViewfinder": "dot-viewfinder",  # dot.viewfinder
}

FONT = "materialdesignicons5-webfont-5.9.55.ttf"
CHARMAP = "materialdesignicons5-webfont-charmap-5.9.55.json"


def main() -> int:
    fonts = Path(os.path.dirname(qtawesome.__file__)) / "fonts"
    font = TTFont(fonts / FONT)
    charmap = json.loads((fonts / CHARMAP).read_text())
    em = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = 24 / em
    lines = [
        "// @parity view/icons",
        "// GENERATED by guitar-tap-project/tooling/parity/gen_web_icons.py — do not edit by hand.",
        "// The Material Design icons the Python edition draws (qtawesome \"mdi.…\"), as SVG paths in a",
        "// 24 × 24 viewBox, so the web shows the same shapes.",
        "export const MDI = {",
    ]
    for key, name in ICONS.items():
        glyph = cmap[int(charmap[name], 16)]
        pen = SVGPathPen(glyphs)
        # Font units, y up, baseline at 0 → a 24 × 24 box, y down, top at the ascent.
        glyphs[glyph].draw(TransformPen(pen, (scale, 0, 0, -scale, 0, ascent * scale)))
        path = pen.getCommands()
        lines.append(f"  {key}: '{path}', // mdi.{name}")
    lines.append("} as const")
    lines.append("")
    out = {p.key: p.root for p in platforms.PLATFORMS}["web"] / "src/components/mdiPaths.ts"
    out.write_text("\n".join(lines))
    print(f"wrote {len(ICONS)} icons to {out}")
    write_custom()
    return 0


def write_custom() -> None:
    """Write the app's own icons into the web and the Python edition, from the SVGs in icons/."""
    import re

    roots = {p.key: p.root for p in platforms.PLATFORMS}
    source = Path(__file__).resolve().parent / "icons"
    svgs = {key: (source / f"{stem}.svg").read_text().strip() for key, stem in CUSTOM.items()}

    web = [
        "// @parity view/icons",
        "// GENERATED by guitar-tap-project/tooling/parity/gen_web_icons.py — do not edit by hand.",
        "// The app's own icons, for the SF Symbols with no Material Design equivalent: each one's SVG markup",
        "// inside a 24 × 24 viewBox, stroked in currentColor. The same drawings as the Python edition's.",
        "export const CUSTOM = {",
    ]
    for key, svg in svgs.items():
        inner = re.sub(r"^<svg[^>]*>|</svg>$", "", svg)
        web.append(f"  {key}: '{inner}', // icons/{CUSTOM[key]}.svg")
    web += ["} as const", ""]
    (roots["web"] / "src/components/customIcons.ts").write_text("\n".join(web))

    py = [
        "# @parity view/icons",
        "# GENERATED by guitar-tap-project/tooling/parity/gen_web_icons.py — do not edit by hand.",
        '"""The app\'s own icons, for the SF Symbols with no Material Design equivalent: each one\'s SVG (24 × 24,',
        "stroked in currentColor), drawn by palette.icon as \"gt.<name>\". The same drawings as the web's.\"\"\"",
        "",
        "SVG = {",
    ]
    for key, svg in svgs.items():
        py.append(f'    "gt.{CUSTOM[key]}": \'{svg}\',')
    py += ["}", ""]
    (roots["python"] / "src/guitar_tap/views/utilities/custom_icons.py").write_text("\n".join(py))
    print(f"wrote {len(CUSTOM)} custom icons to the web and Python")


if __name__ == "__main__":
    sys.exit(main())
